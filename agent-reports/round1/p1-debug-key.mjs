import { createRequire } from 'node:module'
const require = createRequire('C:/Users/robwa/Desktop/Nintendo/blue-ocean-game/package.json')
const { chromium } = require('playwright')
const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader'] })
const context = await browser.newContext({ viewport: { width: 1920, height: 1080 }, reducedMotion: 'no-preference' })
const page = await context.newPage()
page.on('console', m => console.log('CONSOLE', m.type(), m.text()))
page.on('pageerror', e => console.log('PAGEERROR', e.message))
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' })
await page.waitForFunction(() => window.__GAME_READY__ === true)
await page.getByRole('button', { name: /Enter the boardroom/i }).click()
await page.waitForFunction(() => window.__GAME_STATE__?.phase === 'opening')
await page.waitForSelector('#dialogue-panel:not([hidden])')
console.log('after start', await page.evaluate(() => ({ state: window.__GAME_STATE__, active: document.activeElement?.tagName + '#' + document.activeElement?.id, panel: document.getElementById('dialogue-panel').className, hidden: document.getElementById('dialogue-panel').hidden, shown: document.getElementById('dialogue-text').textContent.slice(0,40) })))
await page.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur() })
await page.keyboard.press('Space')
await page.waitForTimeout(500)
console.log('after space', await page.evaluate(() => ({ state: window.__GAME_STATE__, active: document.activeElement?.tagName + '#' + document.activeElement?.id, panel: document.getElementById('dialogue-panel').className, hidden: document.getElementById('dialogue-panel').hidden, shown: document.getElementById('dialogue-text').textContent.slice(0,60), acc: document.getElementById('dialogue-accessible').textContent.slice(0,60) })))
await page.screenshot({ path: 'C:/Users/robwa/Desktop/Nintendo/agent-reports/round1/p1-debug-key.png' })
await browser.close()
